export function getCaminho(id) {
  if (!id) return null;
  const cleanId = String(id).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return caminhos.find(c => c.id === cleanId || cleanId.includes(c.id)) || null;
}
